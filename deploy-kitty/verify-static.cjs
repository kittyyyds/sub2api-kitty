const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const deploy = __dirname;
const root = path.resolve(deploy, '..');
const yaml = require(require.resolve('yaml', { paths: [path.join(root, 'web')] }));
const read = (name) => fs.readFileSync(path.join(deploy, name), 'utf8');
const config = yaml.parse(read('compose.canvas.yml'));
const service = config.services.canvas;
assert.equal(config.name, 'kitty-canvas');
assert.deepEqual(Object.keys(config.services), ['canvas']);
assert.equal(service.build.context, '..');
assert.equal(service.build.dockerfile, 'Dockerfile.kitty');
assert.deepEqual(service.ports, ['127.0.0.1:3101:3101']);
assert.equal(service.read_only, true);
assert.equal(service.user, '1000:1000');
assert.equal(service.volumes, undefined);
assert.equal(service.mem_limit, '1g');
assert.equal(service.cpus, '1.0');
assert.equal(service.tmpfs.length, 2);
assert(service.tmpfs.some((item) => item.startsWith('/app/web/.next/cache:') && item.includes('uid=1000')));
const health = service.healthcheck.test.join(' ');
assert(health.includes('http://127.0.0.1:3101/canvas/canvas'));
assert(!health.includes('canvas-api') && !health.includes('/api/v1/'));
const nginx = read('nginx.canvas.locations.conf.template');
assert(!/^location\s+[^\n]*\/v1\//m.test(nginx));
assert(nginx.includes('proxy_pass http://${SUB_EXISTING_UPSTREAM};'));
assert(nginx.includes('proxy_pass http://127.0.0.1:3101;'));
assert(nginx.includes('location = /canvas/source/kitty-canvas-source.tar.gz'));
assert(nginx.includes('location = /canvas/source/LICENSE'));
const docker = fs.readFileSync(path.join(root, 'Dockerfile.kitty'), 'utf8');
assert(docker.includes('COPY VERSION CHANGELOG.md /app/'));
assert(docker.includes('COPY --from=build /app/web/.next/standalone ./'));
assert(docker.includes('COPY --from=build /app/web/.next/static ./.next/static'));
assert(docker.includes('COPY --from=build /app/web/public ./public'));
assert(docker.includes('CMD ["node", "server.js"]'));
const sourceLicense = fs.readFileSync(path.join(root, 'LICENSE'));
const deliveryLicense = fs.readFileSync(path.join(deploy, 'LICENSE.canvas'));
assert.deepEqual(deliveryLicense, sourceLicense);
assert(read('部署与回退.md').includes('旧自动部署任务不得部署 `.5`'));
console.log('PASS compose YAML, loopback-only port, root build context, read-only root, tmpfs, resource limits, no media volumes');
console.log('PASS healthcheck uses GET /canvas/canvas only; no paid endpoint');
console.log('PASS Nginx preserves /v1 and uses explicit existing-SUB placeholder; source and LICENSE routes present');
console.log('PASS Dockerfile.kitty standalone/static/public paths and node server.js entrypoint');
console.log('PASS LICENSE.canvas byte-for-byte SHA256=' + crypto.createHash('sha256').update(deliveryLicense).digest('hex'));
console.log('NOT RUN Docker build/start, container read-only smoke test, nginx -t, production deployment');
