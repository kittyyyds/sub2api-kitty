// A request uses its latest recorded invoice adjustment, then its frozen
// procurement estimate, then its original account-cost snapshot. Current
// prices, rates and exchange rates never recalculate historical requests.
// An explicitly priced non-USD receipt without FX stays unknown in USD.
const operationsUsageCTE = `WITH operations_usage AS (
 SELECT ul.*, c.cost AS operations_cost, c.source AS operations_source
 FROM usage_logs ul
 LEFT JOIN kitty_procurement_receipts pr ON pr.api_key_id=ul.api_key_id
  AND pr.request_key=CASE WHEN COALESCE(ul.request_id,'')<>'' THEN 'request:'||ul.request_id ELSE 'legacy-row:'||ul.id::text END
  AND pr.source_log_id=ul.id
 LEFT JOIN LATERAL(SELECT a.* FROM kitty_procurement_adjustments a WHERE a.api_key_id=pr.api_key_id AND a.request_key=pr.request_key ORDER BY a.id DESC LIMIT 1) adj ON TRUE
 CROSS JOIN LATERAL(SELECT
  CASE WHEN adj.id IS NOT NULL THEN adj.amount*CASE WHEN adj.currency='USD' THEN 1 ELSE adj.fx_to_usd END
   WHEN pr.estimated_cost IS NOT NULL THEN pr.estimated_cost*CASE WHEN pr.cost_currency='USD' THEN 1 ELSE (pr.rule_snapshot->>'fx_to_usd')::numeric END
   WHEN COALESCE(ul.account_stats_cost,ul.total_cost)>=0 AND COALESCE(ul.account_stats_cost,ul.total_cost)<'Infinity'::numeric
    AND COALESCE(ul.account_rate_multiplier,1)>=0 AND COALESCE(ul.account_rate_multiplier,1)<'Infinity'::numeric
   THEN COALESCE(ul.account_stats_cost,ul.total_cost)*COALESCE(ul.account_rate_multiplier,1) END AS cost,
  CASE WHEN adj.id IS NOT NULL THEN 'reconciled' WHEN pr.estimated_cost IS NOT NULL THEN 'procurement_estimated' ELSE 'account_estimated' END AS source
 ) c
 WHERE ul.created_at >= $1 AND ul.created_at < $2
) `

func (r *usageLogRepository) loadOperationsMetrics(ctx context.Context, data *service.OperationsDashboardData, todayStart, todayEnd, rangeStart, rangeEnd time.Time) error {
	yesterday := todayStart.AddDate(0, 0, -1)
	// Permanent receipts survive usage-log retention. Today and yesterday use
	// the same explicit timezone bounds as the detailed charts.
	var todayCount, yesterdayCount int64
	e := scanSingleRow(ctx, r.sql, `SELECT
  COALESCE(sum(p.actual_cost) FILTER(WHERE u.role='user' AND p.observed_at >= $1 AND p.observed_at < $2),0),
  COALESCE(sum(p.actual_cost) FILTER(WHERE u.role='user' AND p.observed_at >= $3 AND p.observed_at < $1),0),
  COALESCE(sum(p.actual_cost) FILTER(WHERE u.role='user'),0),
  COALESCE(sum(p.actual_cost) FILTER(WHERE u.role IN ('admin','super_admin') AND p.observed_at >= $3 AND p.observed_at < $1),0),
  count(*) FILTER(WHERE u.role='user' AND p.observed_at >= $1 AND p.observed_at < $2),
  count(*) FILTER(WHERE u.role='user' AND p.observed_at >= $3 AND p.observed_at < $1)
 FROM kitty_permanent_usage p JOIN users u ON u.id=p.user_id`, []any{todayStart, todayEnd, yesterday}, &data.Metrics.TodayUserConsumption, &data.Metrics.YesterdayUserConsumption, &data.Metrics.TotalUserConsumption, &data.Metrics.YesterdayAdminConsumption, &todayCount, &yesterdayCount)
	if e != nil {
		return e
	}
	e = scanSingleRow(ctx, r.sql, `SELECT COALESCE(sum(balance) FILTER(WHERE role='user'),0),COALESCE(sum(balance) FILTER(WHERE role IN ('admin','super_admin')),0) FROM users WHERE deleted_at IS NULL`, nil, &data.Metrics.TotalUserBalance, &data.Metrics.AdminBalance)
	if e != nil {
		return e
	}
	// These amounts are credited USD units, not the gateway's cash receipt.
	// PAY-* redemption records are generated by paid orders and are excluded.
	e = scanSingleRow(ctx, r.sql, operationsRechargeCreditsCTE+`SELECT COALESCE(sum(amount) FILTER(WHERE at >= $1 AND at < $2),0),COALESCE(sum(amount) FILTER(WHERE at >= $3 AND at < $1),0) FROM credits WHERE at >= $3 AND at < $2`, []any{todayStart, todayEnd, yesterday}, &data.Metrics.TodayUserRecharge, &data.Metrics.YesterdayUserRecharge)
	if e != nil {
		return e
	}
	// Count the retained V3 probe ledger. The retired Pelican scheduler is not
	// part of this deployment and must not become a dependency of this panel.
	e = scanSingleRow(ctx, r.sql, `WITH monitor AS (
 SELECT started_at AS at,cost_usd, cost_usd IS NULL AS missing FROM channel_monitor_v3_probe_results
 ) SELECT COALESCE(sum(cost_usd) FILTER(WHERE at >= $1 AND at < $2 AND cost_usd>=0),0),
 COALESCE(sum(cost_usd) FILTER(WHERE at >= $3 AND at < $1 AND cost_usd>=0),0),COALESCE(sum(cost_usd) FILTER(WHERE cost_usd>=0),0),
 count(*) FILTER(WHERE at >= $1 AND at < $2 AND missing),count(*) FILTER(WHERE at >= $3 AND at < $1 AND missing)
 FROM monitor`, []any{todayStart, todayEnd, yesterday}, &data.Metrics.TodayMonitorConsumption, &data.Metrics.YesterdayMonitorConsumption, &data.Metrics.TotalMonitorConsumption, &data.Metrics.TodayMonitorUnknown, &data.Metrics.YesterdayMonitorUnknown)
	if e != nil {
		return e
	}
	var todayCost, yesterdayCost float64
	var todayPriced, yesterdayPriced int64
	e = scanSingleRow(ctx, r.sql, operationsUsageCTE+`SELECT
 COALESCE(sum(operations_cost) FILTER(WHERE ul.created_at >= $3),0),COALESCE(sum(operations_cost) FILTER(WHERE ul.created_at < $3),0),
 count(operations_cost) FILTER(WHERE ul.created_at >= $3),count(operations_cost) FILTER(WHERE ul.created_at < $3)
 FROM operations_usage ul JOIN users u ON u.id=ul.user_id WHERE u.role='user'`, []any{yesterday, todayEnd, todayStart}, &todayCost, &yesterdayCost, &todayPriced, &yesterdayPriced)
	if e != nil {
		return e
	}
	data.Metrics.TodayCostUnknown = max(0, todayCount-todayPriced)
	data.Metrics.YesterdayCostUnknown = max(0, yesterdayCount-yesterdayPriced)
	todayProfit := data.Metrics.TodayUserConsumption - todayCost - data.Metrics.TodayMonitorConsumption
	yesterdayProfit := data.Metrics.YesterdayUserConsumption - yesterdayCost - data.Metrics.YesterdayMonitorConsumption
	data.Metrics.TodayRevenue = map[string]*float64{"USD": nil}
	data.Metrics.YesterdayRevenue = map[string]*float64{"USD": nil}
	if data.Metrics.TodayCostUnknown == 0 && data.Metrics.TodayMonitorUnknown == 0 {
		data.Metrics.TodayRevenue["USD"] = &todayProfit
	}
	if data.Metrics.YesterdayCostUnknown == 0 && data.Metrics.YesterdayMonitorUnknown == 0 {
		data.Metrics.YesterdayRevenue["USD"] = &yesterdayProfit
	}
	e = scanSingleRow(ctx, r.sql, operationsUsageCTE+`SELECT count(*),count(*) FILTER(WHERE operations_cost IS NOT NULL AND operations_source='reconciled'),count(*) FILTER(WHERE operations_cost IS NOT NULL AND operations_source='procurement_estimated'),count(*) FILTER(WHERE operations_cost IS NOT NULL AND operations_source='account_estimated'),count(*) FILTER(WHERE operations_cost IS NULL) FROM operations_usage ul JOIN users u ON u.id=ul.user_id WHERE u.role='user'`, []any{rangeStart, rangeEnd}, &data.CostCoverage.Requests, &data.CostCoverage.Reconciled, &data.CostCoverage.ProcurementEstimated, &data.CostCoverage.AccountEstimated, &data.CostCoverage.Unknown)
	if e != nil {
		return e
	}
	return scanSingleRow(ctx, r.sql, `SELECT min(created_at) FROM usage_logs`, nil, &data.DetailsRetainedSince)
}
